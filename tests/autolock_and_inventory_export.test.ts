// 5. Inactivity Auto-Lock timer logic
test('Inactivity timer calculation triggers lock only after timeout threshold', () => {
  const timeoutMinutes = 15;
  const timeoutMs = timeoutMinutes * 60 * 1000; // 900,000 ms

  const now = 1000000;
  // Case A: Active 5 minutes ago (300,000 ms elapsed) -> NOT locked
  const lastActiveA = now - (5 * 60 * 1000);
  const shouldLockA = (now - lastActiveA) >= timeoutMs;
  assert.strictEqual(shouldLockA, false);

  // Case B: Active 16 minutes ago (960,000 ms elapsed) -> LOCKED
  const lastActiveB = now - (16 * 60 * 1000);
  const shouldLockB = (now - lastActiveB) >= timeoutMs;
  assert.strictEqual(shouldLockB, true);

  // Case C: Activity resets timer
  const lastActiveC = now; // just moved mouse
  const shouldLockC = (now - lastActiveC) >= timeoutMs;
  assert.strictEqual(shouldLockC, false);
});
