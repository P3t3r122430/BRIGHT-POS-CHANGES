// 1. Auto-Lock Timeout Validation Schema
const autoLockTimeoutSchema = z.union([
  z.literal(1),
  z.literal(5),
  z.literal(10),
  z.literal(15),
  z.literal(30),
  z.literal(60),
]);

test('Auto-lock timeout schema allows only approved durations (1, 5, 10, 15, 30, 60 minutes)', () => {
  const validDurations = [1, 5, 10, 15, 30, 60];
  for (const d of validDurations) {
    const res = autoLockTimeoutSchema.safeParse(d);
    assert.strictEqual(res.success, true, `Duration ${d} should be allowed`);
  }

  // Reject unrestricted/unapproved values
  const invalidDurations = [0, -5, 2, 7, 20, 120, 'never', null, undefined];
  for (const inv of invalidDurations) {
    const res = autoLockTimeoutSchema.safeParse(inv);
    assert.strictEqual(res.success, false, `Duration ${inv} should be rejected`);
  }
});

// 2. Role-Based Access Control test for Admin-Only actions
interface UserMock {
  id: number;
  username: string;
  role: 'admin' | 'cashier';
}

function checkAdminAuthorization(user?: UserMock): { allowed: boolean; status: number; error?: string } {
  if (!user) {
    return { allowed: false, status: 401, error: 'Access token required. Please log in.' };
  }
  if (user.role !== 'admin') {
    return { allowed: false, status: 403, error: 'Administrative privileges required for this action.' };
  }
  return { allowed: true, status: 200 };
}

test('Role Authorization: Admin is allowed, Cashier is rejected with 403 Forbidden', () => {
  const adminUser: UserMock = { id: 1, username: 'admin', role: 'admin' };
  const cashierUser: UserMock = { id: 2, username: 'cashier', role: 'cashier' };

  const adminAuth = checkAdminAuthorization(adminUser);
  assert.strictEqual(adminAuth.allowed, true);
  assert.strictEqual(adminAuth.status, 200);

  const cashierAuth = checkAdminAuthorization(cashierUser);
  assert.strictEqual(cashierAuth.allowed, false);
  assert.strictEqual(cashierAuth.status, 403);
  assert.strictEqual(cashierAuth.error, 'Administrative privileges required for this action.');

  const anonAuth = checkAdminAuthorization(undefined);
  assert.strictEqual(anonAuth.allowed, false);
  assert.strictEqual(anonAuth.status, 401);
});

// 3. Stock Export Formatting and Generation
interface ProductExportItem {
  id: number;
  sku: string;
  barcode: string | null;
  name: string;
  category_name: string;
  unit: string;
  stock_quantity: number;
  minimum_stock: number;
  cost_price: number;
  selling_price: number;
  total_cost_value: number;
  total_retail_value: number;
  potential_profit: number;
  stock_status: 'IN_STOCK' | 'LOW_STOCK' | 'OUT_OF_STOCK';
  supplier: string | null;
  updated_at: string;
}

function generateStockListExportData(products: ProductExportItem[], adminName: string, dateStr: string) {
  let totalUnits = 0;
  let totalCostValuation = 0;
  let totalRetailValuation = 0;
  let totalPotentialProfit = 0;

  for (const p of products) {
    totalUnits += p.stock_quantity;
    totalCostValuation += p.total_cost_value;
    totalRetailValuation += p.total_retail_value;
    totalPotentialProfit += p.potential_profit;
  }

  const rows: any[][] = [
    ['BRIGHT CYBER & ICT'],
    ['CURRENT INVENTORY / STOCK LIST'],
    [`Generated date and time: ${dateStr}`, '', `Generated by: Admin (${adminName})`],
    [
      `Total Products: ${products.length}`,
      `Total Units: ${totalUnits}`,
      `Total Cost Valuation: KES ${totalCostValuation.toFixed(2)}`,
      `Total Retail Valuation: KES ${totalRetailValuation.toFixed(2)}`,
    ],
    [],
    [
      '#',
      'SKU / Product Code',
      'Barcode',
      'Product Name',
      'Category',
      'Unit',
      'Current Quantity',
      'Minimum Stock Alert',
      'Stock Status',
      'Cost Price (KES)',
      'Selling Price (KES)',
      'Total Cost Value (KES)',
      'Total Retail Value (KES)',
      'Potential Profit (KES)',
      'Supplier',
      'Last Updated'
    ]
  ];

  products.forEach((p, idx) => {
    rows.push([
      idx + 1,
      p.sku,
      p.barcode || 'N/A',
      p.name,
      p.category_name,
      p.unit,
      p.stock_quantity,
      p.minimum_stock,
      p.stock_status,
      p.cost_price,
      p.selling_price,
      p.total_cost_value,
      p.total_retail_value,
      p.potential_profit,
      p.supplier || 'N/A',
      p.updated_at
    ]);
  });

  return {
    rows,
    totalUnits,
    totalCostValuation,
    totalRetailValuation,
    totalPotentialProfit,
  };
}

